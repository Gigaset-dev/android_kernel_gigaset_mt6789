static int lcm_setbacklight_cmdq(void *dsi, dcs_write_gce cb, void *handle,
				 unsigned int level)
{
	unsigned char bl_tb[] = {0x51,0x00,0x00};
	unsigned char hbm_tb[] = {0x51,0x0F,0xFF};

	if (level > 4095) {
		if (level == 4096) {
			if (!cb)
				return -1;
			pr_err("%s panel into HBM", __func__);
			cb(dsi, handle, hbm_tb, ARRAY_SIZE(hbm_tb));
		} else if (level == 4097) {
			if (rawlevel <= 0x1FFF) {
				bl_tb[1] = (unsigned char)((rawlevel>>8)&0x1f);
				bl_tb[2] = (unsigned char)(rawlevel&0xff);
			} else {
				pr_err("%s err, rawlevel=%d\n", __func__, rawlevel);
			}
			if (!cb)
				return -1;
			pr_err("%s panel out HBM, rawlevel=%d, bl_tb[1]=0x%x, bl_tb[2]=0x%x\n",
				__func__, rawlevel, bl_tb[1], bl_tb[2]);
			cb(dsi, handle, bl_tb, ARRAY_SIZE(bl_tb));
		}
	} else {
		if (level) {
			rawlevel = level*0x1FFF/255;
		} else {
			rawlevel = 0;
		}
		if (rawlevel <= 0x1FFF) {
			bl_tb[1] = (unsigned char)((rawlevel>>8)&0x1f);
			bl_tb[2] = (unsigned char)(rawlevel&0xff);
			if (!cb)
				return -1;
			cb(dsi, handle, bl_tb, ARRAY_SIZE(bl_tb));
			pr_err("%s level=%d, rawlevel=%d, bl_tb[1]=0x%x, bl_tb[2]=0x%x\n",
				__func__, level, rawlevel, bl_tb[1], bl_tb[2]);
		} else {
			pr_err("%s err, rawlevel=%d\n", __func__, rawlevel);
		}
	}
	
	return 0;
}

